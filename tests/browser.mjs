import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,executablePath:'/usr/bin/chromium'});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
await page.route('**/api/menu*',r=>r.fulfill({status:502,contentType:'application/json',body:JSON.stringify({error:'검증용 수집 오류'})}));
await page.goto('http://127.0.0.1:3000');
await page.getByRole('heading',{name:'지금은 식단을 가져오지 못했어요'}).waitFor();
await page.getByRole('button',{name:'♡ 관심 메뉴',exact:true}).click();
await page.getByRole('textbox',{name:'관심 키워드'}).fill('제육');
await page.getByRole('button',{name:'추가 +'}).click();
await page.reload();
await page.getByRole('button',{name:'♡ 관심 메뉴',exact:true}).click();
await page.getByRole('button',{name:'제육 ×'}).waitFor();
const date=new Intl.DateTimeFormat('sv-SE',{timeZone:'Asia/Seoul'}).format(new Date());
await page.unroute('**/api/menu*');
await page.route('**/api/menu*',r=>r.fulfill({contentType:'application/json',body:JSON.stringify({fetchedAt:new Date().toISOString(),menus:[{id:'test',date,meal:'중식',items:['제육볶음','쌀밥','김치'],sourceUrl:'https://dorm.korea.ac.kr/'}]})}));
await page.reload();
await page.getByText('제육볶음',{exact:true}).waitFor();
await page.getByRole('button',{name:/알림함/}).click();
await page.getByRole('heading',{name:date+' · 중식'}).waitFor();
await page.setViewportSize({width:390,height:844});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
await page.screenshot({path:'/tmp/anam-mobile.png',fullPage:true});
console.log('Browser checks passed: source error, preference persistence, fixture matching, mobile overflow. Fixture data is not live crawling.');
await browser.close();
